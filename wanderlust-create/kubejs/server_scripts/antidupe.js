//
// 1) Crafting Blueprint × Item Filter
//    Create issue #4339 — подтверждён, ОТКРЫТ, назначен на Create 6.0.11.
//    У нас 6.0.10, конфигом не лечится, официального патча нет.
//
//    Механика: в слоты Crafting Blueprint кладут пустой фильтр (принимает
//    любой предмет), тот же фильтр — в слот результата. Игрок держит предметы
//    в хотбаре, жмёт по бланку и получает лишние предметы: столько, сколько
//    входных фильтров минус один. Два и больше слотов усиливают эффект.
//
//    Лечим в корне: убираем сам Crafting Blueprint из крафта. Мир после
//    вайпа чистый, ни у кого его на руках нет, скрафтить будет нельзя —
//    значит и связки «бланк + фильтр» не возникнет.
//
//    Фильтры (filter / attribute_filter / package_filter) НЕ трогаем: без
//    них не живёт вся автоматизация Create, а сами по себе они безопасны.
//    Дюп даёт именно бланк.
//
//    Когда выйдет Create 6.0.11 с фиксом — этот блок можно снять и вернуть
//    бланк игрокам.

ServerEvents.recipes(event => {
    event.remove({ output: 'create:crafting_blueprint' })
    console.info('[antidupe] рецепт create:crafting_blueprint убран (Create #4339)')
})

// Убираем из выдачи /give и из поиска, чтобы предмет не всплыл окольным путём
// (сундуки лута, торговцы, рецепты других модов, ссылающиеся на него).
ServerEvents.tags('item', event => {
    event.removeAllTagsFrom('create:crafting_blueprint')
})
